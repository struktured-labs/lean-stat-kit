#!/usr/bin/env python3
"""Emit a Lean data module (and a canonical byte file) from numeric CSV columns.

Outside the proof: the emitted module is *checked* inside Lean, either by the kernel
(`--embed`: the canonical bytes are embedded and `parse_ok` proves
`parseRows k bytes = some rows`) or at runtime for large files (`<Module>Check.lean`: runs the
proved parser on the on-disk canonical file and exits 0 only if it returns exactly `rows`).

Values must be unsigned decimals with at most --scale fractional digits; each is stored exactly
as the integer value*10^scale (fail-closed otherwise). Stdlib only.

usage: emit_csv_module.py --input data.csv --cols date,close [--scale 2] [--no-header]
       --module Examples.Foo.Data --lean-out Examples/Foo/Data.lean --canon-out data/foo.csv [--embed]
"""
import argparse, csv, hashlib, re, sys

ap = argparse.ArgumentParser()
ap.add_argument("--input", required=True)
ap.add_argument("--cols", required=True, help="comma-separated column names (or 0-based indices with --no-header)")
ap.add_argument("--scale", default="0", help="decimal places: one value for all columns, or one per column (comma-separated)")
ap.add_argument("--no-header", action="store_true")
ap.add_argument("--names", default=None, help="Lean names for the columns (default: --cols)")
ap.add_argument("--module", required=True)
ap.add_argument("--lean-out", required=True)
ap.add_argument("--canon-out", required=True)
ap.add_argument("--embed", action="store_true")
a = ap.parse_args()

raw = open(a.input, "rb").read()
text = raw.decode("utf-8")
rdr = list(csv.reader(text.splitlines()))
if not rdr: sys.exit("emit: FAIL: empty input")
cols = a.cols.split(",")
scales = [int(x) for x in a.scale.split(",")]
if len(scales) == 1: scales = scales * len(cols)
if len(scales) != len(cols): sys.exit("emit: FAIL: --scale count != --cols count")
if a.no_header:
    idx = [int(c) for c in cols]; body = rdr
else:
    hdr = [h.strip() for h in rdr[0]]
    try: idx = [hdr.index(c) for c in cols]
    except ValueError as e: sys.exit(f"emit: FAIL: column not found: {e}")
    body = rdr[1:]
num = re.compile(r"^(\d+)(?:\.(\d+))?$")
def fix(s, r, c, sc):
    m = num.match(s.strip())
    if not m: sys.exit(f"emit: FAIL: row {r} col {c}: not an unsigned decimal: {s!r}")
    ip, fp = m.group(1), m.group(2) or ""
    if len(fp) > sc: sys.exit(f"emit: FAIL: row {r} col {c}: more than {sc} decimals: {s!r}")
    return int(ip + fp.ljust(sc, "0"))
rows = []
for r, row in enumerate(body):
    if not row: continue
    rows.append([fix(row[i], r, cols[j], scales[j]) for j, i in enumerate(idx)])
if not rows: sys.exit("emit: FAIL: no data rows")
canon = "".join(",".join(str(v) for v in row) + "\n" for row in rows).encode()
open(a.canon_out, "wb").write(canon)
k = len(cols)
ns = a.module
lit = "[\n" + ",\n".join("  [" + ", ".join(str(v) for v in row) + "]" for row in rows) + "\n]"
out = [f"/- GENERATED by tools/emit_csv_module.py. Do not edit.",
       f"   source {a.input} sha256 {hashlib.sha256(raw).hexdigest()} ({len(raw)} bytes)",
       f"   columns {cols} scales {scales} (value = field / 10^scale); {len(rows)} rows",
       f"   canonical {a.canon_out} sha256 {hashlib.sha256(canon).hexdigest()} ({len(canon)} bytes) -/",
       "import StatKit.Csv", "", f"namespace {ns}", "",
       f"def arity : Nat := {k}", f"/-- decimal places per column -/", f"def scales : List Nat := {scales}", "",
       "set_option maxRecDepth 100000 in",
       f"def rows : List (List Nat) := {lit}", ""]
names = a.names.split(",") if a.names else cols
if len(names) != len(cols): sys.exit("emit: FAIL: --names count != --cols count")
for j, c in enumerate(names):
    out.append(f"/-- column `{c}` (integer, value × 10^{scales[j]}) -/")
    out.append(f"def col_{re.sub(r'[^A-Za-z0-9_]', '_', c)} : List Nat := StatKit.Csv.column {j} rows")
out.append("")
if a.embed:
    out += [f"/-- the canonical bytes, embedded -/",
            f"def canonical : String := {canon.decode()!r}".replace("'", '"'),
            "",
            "set_option maxRecDepth 100000 in",
            "/-- kernel-checked: the proved parser maps the embedded bytes to exactly `rows` -/",
            f"theorem parse_ok : StatKit.Csv.parseRows {k} (StatKit.Csv.bytesOf canonical) = some rows := by",
            "  decide +kernel", "",
            "theorem rows_spec : StatKit.Csv.printRows rows = StatKit.Csv.bytesOf canonical ∧",
            f"    ∀ r ∈ rows, r.length = {k} :=",
            "  StatKit.Csv.rows_of_parse (by decide) parse_ok", ""]
out += [f"end {ns}", ""]
open(a.lean_out, "w").write("\n".join(out))
if not a.embed:
    chk = a.lean_out[:-5] + "Check.lean"
    open(chk, "w").write(f"""/- GENERATED by tools/emit_csv_module.py. Runtime bridge (not a kernel proof): run the proved
   parser on the on-disk canonical file and require exactly `{ns}.rows`. Exit 0 only on equality. -/
import {ns}

def main (args : List String) : IO UInt32 := do
  let path := args.headD "{a.canon_out}"
  let bytes ← IO.FS.readBinFile path
  match StatKit.Csv.parseRows {k} bytes.toList with
  | none => IO.eprintln "check: FAIL: parser rejected the file"; return 1
  | some xs =>
    if xs == {ns}.rows then
      IO.println s!"check: OK bytes={{bytes.size}} rows={{xs.length}} parseRows(file) = some rows"; return 0
    else
      IO.eprintln "check: FAIL: parsed rows differ from the embedded literal"; return 1
""")
print(f"emit: OK rows={len(rows)} arity={k} scales={scales} canon_bytes={len(canon)} embed={a.embed}")
