#!/usr/bin/env python3
"""Emit Audit.lean: `#print axioms` for EVERY theorem declared in the given modules.
Usage: gen_audit.py OUT.lean Mod/Path.lean ...   (prints the theorem count on stdout)"""
import re, sys
out, files = sys.argv[1], sys.argv[2:]
names, mods = [], []
for f in files:
    mods.append(f[:-5].replace("/", "."))
    ns = []
    for line in open(f, encoding="utf-8"):
        m = re.match(r"^namespace\s+(\S+)", line)
        if m: ns.append(m.group(1)); continue
        m = re.match(r"^end\s+(\S+)\s*$", line)
        if m and ns and ns[-1] == m.group(1): ns.pop(); continue
        m = re.match(r"^(?:private\s+)?(?:theorem|lemma)\s+([^\s(:{\[]+)", line)
        if m:
            if line.startswith("private"): sys.exit(f"gen_audit: FAIL: private theorem in {f}")
            names.append(".".join(ns + [m.group(1)]))
with open(out, "w") as o:
    o.write("/- GENERATED by tools/gen_audit.py: axioms of every theorem in the kit and examples. -/\n")
    for m in mods: o.write(f"import {m}\n")
    o.write("\n")
    for n in names: o.write(f"#print axioms {n}\n")
print(len(names))
